class Mahasiswa:
    def __init__(self, Id_mahasiswa=None, nama=None, jurusan=None, alamat=None, tahun_masuk=None, Id_kelas=None, Id_matakuliah=None):
        self.Id_mahasiswa = Id_mahasiswa
        self.nama = nama
        self.jurusan = jurusan
        self.alamat = alamat
        self.tahun_masuk = tahun_masuk
        self.Id_kelas = Id_kelas
        self.Id_matakuliah = Id_matakuliah
